-- Propuesta homologada para revision; no aplicar como migracion aun.
-- Una fila por codigo_ua + modalidad + fecha_corte.
-- El CSV incluye longitude/latitude; la carga construira geom con longitude primero.
-- Los codigos DPA se guardan como texto indexado, sin restricciones FK.

CREATE TABLE ua_amenazas (
    id                                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_corte                                     DATE NOT NULL,
    created_at                                      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                                      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    codigo_ua                                       TEXT NOT NULL,
    nombre_ua                                       TEXT NOT NULL,
    servicio                                        TEXT NOT NULL,
    modalidad                                       TEXT NOT NULL,
    modalidad_etiqueta_reporte                      TEXT NOT NULL,
    zona_planificacion                              TEXT NOT NULL,
    codigo_distrito                                 TEXT NOT NULL,
    unidad_desconcentrada                           TEXT NOT NULL,
    region                                          TEXT NOT NULL,
    province_id                                     TEXT NOT NULL,
    canton_id                                       TEXT NOT NULL,
    parish_id                                       TEXT NOT NULL,
    codigo_parroquia_origen                         TEXT NOT NULL,
    provincia_origen                               TEXT NOT NULL,
    canton_origen                                  TEXT NOT NULL,
    parroquia_origen                               TEXT NOT NULL,
    codigo_cabecera_cantonal                        TEXT NOT NULL,
    nombre_cabecera_cantonal                        TEXT NOT NULL,
    tipo_atencion                                   TEXT NOT NULL,
    area                                            TEXT NOT NULL,
    tipo_administracion                             TEXT NOT NULL,
    cooperante                                      TEXT NOT NULL,
    usuarios_hombres                                INTEGER,
    usuarios_mujeres                                INTEGER,
    usuarios_hombres_mapa                           INTEGER NOT NULL,
    usuarios_mujeres_mapa                           INTEGER NOT NULL,
    usuarios_total                                  INTEGER NOT NULL,
    direccion                                       TEXT,
    referencia                                      TEXT,
    ruc                                             TEXT,
    asistencia_promedio                            NUMERIC,
    asistencia_norma_tecnica                       INTEGER,
    usuarios_con_registro_social_2018                INTEGER,
    usuarios_sin_registro_social_2018               INTEGER,
    usuarios_extrema_pobreza_2018                   INTEGER,
    usuarios_pobreza_2018                           INTEGER,
    usuarios_no_pobres_2018                         INTEGER,
    usuarios_con_registro_social_2025                INTEGER,
    usuarios_sin_registro_social_2025               INTEGER,
    usuarios_extrema_pobreza_2025                   INTEGER,
    usuarios_pobreza_2025                           INTEGER,
    usuarios_no_pobres_2025                         INTEGER,
    coordenada_x_utm                                NUMERIC NOT NULL,
    coordenada_y_utm                                NUMERIC NOT NULL,
    geom                                            geometry(Point, 4326) NOT NULL,
    nivel_susceptibilidad_inundaciones              SMALLINT NOT NULL,
    nivel_susceptibilidad_movimientos_en_masa       SMALLINT NOT NULL,
    nivel_susceptibilidad_sequias                   SMALLINT NOT NULL,
    nivel_susceptibilidad_incendios_forestales      SMALLINT NOT NULL,
    categoria_susceptibilidad_inundaciones          TEXT NOT NULL,
    categoria_susceptibilidad_movimientos_en_masa   TEXT NOT NULL,
    categoria_susceptibilidad_sequias               TEXT NOT NULL,
    categoria_susceptibilidad_incendios_forestales  TEXT NOT NULL,
    multiamenaza                                    TEXT,
    CONSTRAINT uq_ua_amenazas_corte_codigo_modalidad
        UNIQUE (fecha_corte, codigo_ua, modalidad)
);

CREATE INDEX idx_ua_amenazas_province
    ON ua_amenazas (province_id);

CREATE INDEX idx_ua_amenazas_canton
    ON ua_amenazas (canton_id);

CREATE INDEX idx_ua_amenazas_parish
    ON ua_amenazas (parish_id);

CREATE INDEX idx_ua_amenazas_servicio
    ON ua_amenazas (servicio);

CREATE INDEX idx_ua_amenazas_modalidad
    ON ua_amenazas (modalidad);

CREATE INDEX idx_ua_amenazas_geom
    ON ua_amenazas USING GIST (geom);

CREATE FUNCTION ua_amenazas_set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ua_amenazas_updated_at
    BEFORE UPDATE ON ua_amenazas
    FOR EACH ROW
    EXECUTE FUNCTION ua_amenazas_set_updated_at();
